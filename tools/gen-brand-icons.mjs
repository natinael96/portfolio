/**
 * Generates src/changelog/brandIcons.ts from simple-icons.
 *
 *   node tools/gen-brand-icons.mjs
 *
 * Why generate instead of importing at runtime: simple-icons ships ~3,460
 * icons. Extracting the two dozen we use keeps the package a devDependency
 * and puts only the paths we render into the bundle.
 *
 * Each icon also gets per-theme hexes. Official brand colours are picked for
 * logo sheets, not for 13px marks on paper or on near-black: JavaScript
 * yellow vanishes on white and Next.js black vanishes on dark. We nudge the
 * outliers toward legibility along their own hue and leave the rest alone.
 */
import * as si from 'simple-icons'
import { writeFileSync } from 'node:fs'

/** label in content/changelog.ts -> simple-icons export, or null for no mark. */
const WANT = {
  TypeScript: 'siTypescript',
  JavaScript: 'siJavascript',
  Python: 'siPython',
  SQL: null,
  Kotlin: 'siKotlin',
  FastAPI: 'siFastapi',
  Django: 'siDjango',
  NestJS: 'siNestjs',
  'Node.js': 'siNodedotjs',
  REST: null,
  WebSockets: null,
  GraphQL: 'siGraphql',
  React: 'siReact',
  'Next.js': 'siNextdotjs',
  'Vue 3': 'siVuedotjs',
  Angular: 'siAngular',
  'Tailwind CSS': 'siTailwindcss',
  PostgreSQL: 'siPostgresql',
  MongoDB: 'siMongodb',
  Redis: 'siRedis',
  Docker: 'siDocker',
  Kubernetes: 'siKubernetes',
  'GitHub Actions': 'siGithubactions',
  Caddy: 'siCaddy',
  // simple-icons carries no Amazon/AWS mark; that chip stays text-only.
  'AWS (EC2, S3)': null,
  Git: 'siGit',
  'Jetpack Compose': 'siJetpackcompose',
  'Material 3': 'siMaterialdesign',
  'scikit-learn': 'siScikitlearn',
  pandas: 'siPandas',
  NumPy: 'siNumpy',
  'LLM APIs': null,
}

const GROUND_LIGHT = [253, 252, 250]
const GROUND_DARK = [25, 26, 24]
/** Marks sit beside their own text label, so they need presence, not AA. */
const MIN_RATIO = 2.2

const toRgb = (hex) => [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16))
const toHex = (rgb) => rgb.map((c) => Math.round(c).toString(16).padStart(2, '0')).join('')
const lin = (c) => (c / 255 <= 0.03928 ? c / 255 / 12.92 : ((c / 255 + 0.055) / 1.055) ** 2.4)
const lum = (rgb) => 0.2126 * lin(rgb[0]) + 0.7152 * lin(rgb[1]) + 0.0722 * lin(rgb[2])
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m)
  return (x + 0.05) / (y + 0.05)
}
const mix = (rgb, target, amount) => rgb.map((c, i) => c + (target[i] - c) * amount)

/** Walk the colour toward black or white until it reads against `ground`. */
function fit(hex, ground) {
  const target = lum(ground) > 0.4 ? [0, 0, 0] : [255, 255, 255]
  let rgb = toRgb(hex)
  for (let step = 0; step <= 20; step++) {
    if (ratio(rgb, ground) >= MIN_RATIO) break
    rgb = mix(toRgb(hex), target, step / 20)
  }
  return toHex(rgb)
}

let rows = ''
let count = 0
const skipped = []
for (const [label, key] of Object.entries(WANT)) {
  if (!key) {
    skipped.push(label)
    continue
  }
  const icon = si[key]
  if (!icon) throw new Error(`simple-icons has no export "${key}" for ${label}`)
  const light = fit(icon.hex, GROUND_LIGHT)
  const dark = fit(icon.hex, GROUND_DARK)
  rows +=
    `  ${JSON.stringify(label)}: { path: ${JSON.stringify(icon.path)}, ` +
    `light: '#${light}', dark: '#${dark}' },\n`
  count++
}

writeFileSync(
  'src/changelog/brandIcons.ts',
  `/**
 * GENERATED by tools/gen-brand-icons.mjs — do not edit by hand.
 *
 * Brand marks for the Stack section. \`light\` and \`dark\` are the official
 * brand hex nudged along its own hue until it reads on that theme's ground;
 * most are untouched. Labels absent here (${skipped.join(', ')}) have no
 * mark and render text only.
 */
export interface BrandIcon {
  /** Single path on a 24x24 viewBox. */
  path: string
  light: string
  dark: string
}

export const brandIcons: Record<string, BrandIcon> = {
${rows}}
`,
)
console.log(`wrote ${count} icons (${skipped.length} text-only: ${skipped.join(', ')})`)
